import type { KnowledgePackObject } from "./pack-schema";
import { isMemberVisibleKnowledge } from "./governance";

function rel(target: string, relationType: string) {
  return { target_stable_key: target, relation_type: relationType };
}

function sourced(
  partial: Omit<KnowledgePackObject, "relations" | "aliases" | "service_families" | "capabilities" | "methods" | "business_problems" | "industries" | "dimensions" | "engagement_stages"> &
    Partial<Pick<KnowledgePackObject, "relations" | "aliases" | "service_families" | "capabilities" | "methods" | "business_problems" | "industries" | "dimensions" | "engagement_stages">>,
): KnowledgePackObject {
  return {
    aliases: [],
    service_families: [],
    capabilities: [],
    methods: [],
    business_problems: [],
    industries: [],
    dimensions: [],
    engagement_stages: [],
    relations: [],
    ...partial,
  };
}

function officialResult(input: {
  key: string;
  name: string;
  description: string;
  locator: string;
  industries: string[];
  capabilities: string[];
  methods?: string[];
  problems?: string[];
  families?: string[];
  attribution?: "named" | "anonymized";
  relations?: { target_stable_key: string; relation_type: string }[];
}): KnowledgePackObject {
  return sourced({
    stable_key: `result.${input.key}`,
    canonical_name: input.name,
    object_type: "case",
    knowledge_nature: "delivered_result",
    outcome_status: "delivered",
    description: input.description,
    service_families: input.families ?? ["Manufacturing"],
    capabilities: input.capabilities,
    methods: input.methods ?? [],
    business_problems: input.problems ?? [],
    industries: input.industries,
    source_references: [{ source_id: "src-efeso-official-client-results", locator: input.locator }],
    visibility_level: "public",
    confidentiality_level: "public",
    approved_for_matching: true,
    approved_for_display: true,
    origin: "public_official",
    client_attribution: input.attribution ?? "anonymized",
    catalog_section: "cases_and_results",
    relations: input.relations ?? input.capabilities.map((name) => rel(capabilityKey(name), "demonstrates_capability")),
  });
}

